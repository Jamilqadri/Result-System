import React, { useState, useRef, useEffect } from 'react';
import { Madrasa, MadrasaClass } from '../../types';
import {
  getNextMadrasaCode,
  getStoredMadaris,
  persistMadrasa,
  persistClass,
  getStoredDefaultClasses,
  fetchStoredDefaultClasses,
  DEFAULT_REGISTRATION_CLASSES,
  DEFAULT_CLASSES_UPDATED_EVENT,
  getCentralKaifiyatRules,
  getCentralPassingSettings,
  fetchCentralSheetUrl,
} from '../../utils/storage';
import { INDIAN_STATES_DISTRICTS } from '../../utils/indiaLocations';
import { DEFAULT_CLASS_SUBJECTS, buildClassTabCsv } from '../../utils/sheetGenerator';
